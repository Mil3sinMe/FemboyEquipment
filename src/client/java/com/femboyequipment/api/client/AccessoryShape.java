package com.femboyequipment.api.client;

/** The built-in 3D accessory models that addons can reuse with their own textures. */
public enum AccessoryShape {
	/** Pointy ears on top of the head. Texture layout: see femboyequipment:textures/entity/accessory/cat_ears.png (16x16). */
	CAT_EARS,
	/** A curly tail on the lower back (sways). Texture layout: cat_tail.png (16x16). */
	CAT_TAIL,
	/** Tall ears on top of the head. Texture layout: bunny_ears.png (16x16). */
	BUNNY_EARS,
	/** A fluffy pom-pom tail. Texture layout: bunny_tail.png (16x16). */
	BUNNY_TAIL,
	/** A flared skirt around the waist. Texture layout: pleated_skirt.png (64x32). */
	SKIRT
}
